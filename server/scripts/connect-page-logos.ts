import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { inlineSvg, isInertSvg } from "../src/api/connect-pages/svg.ts";

const source = resolve(import.meta.dirname, "../../dashboard/public/integrations");
const target = resolve(import.meta.dirname, "../src/api/connect-pages/logos.ts");

const entries = readdirSync(source)
  .filter((name) => name.endsWith(".svg"))
  .sort()
  .map((name) => {
    const svg = inlineSvg(readFileSync(resolve(source, name), "utf8"));
    if (!isInertSvg(svg)) throw new Error(`${name} has something that runs or loads; it cannot be inlined`);
    return `  ${JSON.stringify(name.replace(/\.svg$/, ""))}: ${JSON.stringify(svg)},`;
  });

writeFileSync(target, `/**
 * Integration marks for the hosted connect pages, inlined so a page loads nothing.
 * Generated by scripts/connect-page-logos.ts from dashboard/public/integrations: edit those, not this.
 */
export const LOGOS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`);
console.log(`Wrote ${entries.length} logos to ${target}`);
